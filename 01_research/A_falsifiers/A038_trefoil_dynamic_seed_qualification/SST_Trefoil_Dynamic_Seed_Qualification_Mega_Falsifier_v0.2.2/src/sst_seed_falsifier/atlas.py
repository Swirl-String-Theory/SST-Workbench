"""Prospective realization holdout, NOT an unseen-parent or external-validation atlas.

Freeze -> generate test shard -> score -> reveal. Reserve random seed remains
sealed and reserve geometries are deliberately not generated by this module.
"""
from pathlib import Path
from datetime import datetime, timezone
import argparse
import secrets
import sys
import numpy as np

from .evidence import code_manifest, file_sha256, object_sha256, tree_manifest
from .io import dump_json, load_json, geom_sha
from .geometry import normalize_length, resample_closed, normal_frame, align_cyclic
from .topology_witness import trefoil_witness

PARENTS = {
    'fremlin_fourier': 'Fremlin_FourierSeries/fremlin/3_1/knot.3_1.short',
    'gilbert_sono_fourier': 'Knot_Library/Sources/Ideal_Gilbert/extracted/3_1/3_1_AB.txt',
}
LIBRARY = 'Knot_Library/SST_Knot_Library/SST_Knot_Library_v0.2.3'


def dependencies(repo):
    repo=Path(repo)
    rows=[{'path':p,'sha256':file_sha256(repo/p)} for p in PARENTS.values()]
    for row in tree_manifest(repo/LIBRARY/'sst_knotlib',{'.py','.json','.sha256','.pyd'}):
        rows.append({**row,'path':LIBRARY+'/sst_knotlib/'+row['path']})
    return rows


def freeze(repo, out, config, protocol):
    out=Path(out); private=out/'sealed'
    if out.exists() and any(out.iterdir()):
        raise FileExistsError('REFUSING_TO_OVERWRITE_ATLAS')
    private.mkdir(parents=True)
    test_seed=secrets.token_hex(32); reserve_seed=secrets.token_hex(32)
    dump_json(private/'seeds.json',{'test':test_seed,'reserve':reserve_seed})
    package=Path(__file__).resolve().parents[2]
    record={'format':'SST-PROSPECTIVE-ATLAS-1','created_utc':datetime.now(timezone.utc).isoformat(),
            'scope':'new_randomized_realizations_of_previously_available_parent_families',
            'parent_level_held_out':False,'statistical_independence_claim':False,
            'families':['fremlin_fourier','gilbert_sono_fourier','sst_braid_closure'],
            'independence_basis':'distinct_geometry_construction_lineages_not_independent_physical_observations',
            'test_seed_sha256':object_sha256(test_seed),'reserve_seed_sha256':object_sha256(reserve_seed),
            'code_manifest':code_manifest(package),'dependencies':dependencies(repo),
            'config':load_json(config),'phase_b_protocol':load_json(protocol),
            'config_file_sha256':file_sha256(config),'protocol_file_sha256':file_sha256(protocol),
            'design':{'test_draws_per_family':2,'reserve_draws_per_family':2,'n':128,
                      'scale_range':[.985,1.015],'normal_amplitude':.003,'modes':[2,3,4],
                      'replacement_on_failure':False,'qualification_resolutions':[64,96,128]}}
    dump_json(out/'PREREGISTRATION.json',record)
    dump_json(out/'PREREGISTRATION_COMMITMENT.json',{'sha256':object_sha256(record)})
    return record


def verify_freeze(repo,out):
    out=Path(out); record=load_json(out/'PREREGISTRATION.json')
    if object_sha256(record)!=load_json(out/'PREREGISTRATION_COMMITMENT.json')['sha256']:
        raise ValueError('ATLAS_PROTOCOL_COMMITMENT_MISMATCH')
    if record['code_manifest']!=code_manifest(Path(__file__).resolve().parents[2]):
        raise ValueError('ATLAS_FROZEN_CODE_MISMATCH')
    if record['dependencies']!=dependencies(repo):
        raise ValueError('ATLAS_FROZEN_DEPENDENCY_MISMATCH')
    return record


def load_parents(repo):
    repo=Path(repo)
    sys.path.insert(0,str(repo/LIBRARY))
    from sst_knotlib.formats import load_geometry
    from sst_knotlib.braid import braid_closure
    return {**{family:load_geometry(repo/path).points for family,path in PARENTS.items()},
            'sst_braid_closure':braid_closure(2,[1,1,1],resample_n=512)}


def generate_test(repo,out):
    out=Path(out); record=verify_freeze(repo,out)
    test=out/'test_atlas'
    if test.exists(): raise FileExistsError('TEST_ATLAS_ALREADY_GENERATED')
    seeds=load_json(out/'sealed/seeds.json')
    if object_sha256(seeds['test'])!=record['test_seed_sha256']:
        raise ValueError('ATLAS_TEST_SEED_COMMITMENT_MISMATCH')
    rng=np.random.default_rng(int(seeds['test'],16)); design=record['design']
    parents=load_parents(repo); test.mkdir()
    records=[]; geometries=[]; topology=[]; pairwise=[]
    for fi,(family,parent) in enumerate(parents.items()):
        base=normalize_length(resample_closed(parent,design['n']))
        for draw in range(design['test_draws_per_family']):
            scales=rng.uniform(*design['scale_range'],size=3)
            y=base*scales
            _,normal,_=normal_frame(y); phase=rng.uniform(0,2*np.pi)
            mode=int(rng.choice(design['modes']))
            y=y+design['normal_amplitude']*np.cos(2*np.pi*mode*np.arange(len(y))/len(y)+phase)[:,None]*normal
            y=normalize_length(resample_closed(y,design['n']))
            name=f'trefoil_family{fi+1}_draw{draw+1}.xyz'
            checks={str(n):trefoil_witness(normalize_length(resample_closed(y,n))) for n in design['qualification_resolutions']}
            passed=all(c['accepted'] for c in checks.values())
            for previous,z in geometries:
                d=min(align_cyclic(y,z,1)[1],align_cyclic(y[::-1],z,1)[1])
                pairwise.append({'a':previous,'b':name,'aligned_rms':float(d)})
            geometries.append((name,y))
            np.savetxt(test/name,np.vstack([y,y[0]]),fmt='%.17g')
            records.append({'path':name,'family_id':family,'topology':'trefoil','components':1,
                            'held_out':True,'held_out_scope':'prospective_randomized_realization_only',
                            'parent_level_held_out':False,'provenance':PARENTS.get(family,LIBRARY+'/sst_knotlib/braid.py: braid_closure(2,[1,1,1])'),
                            'geometry_sha256':geom_sha(y),'file_sha256':file_sha256(test/name),
                            'parent_geom_sha256':geom_sha(base),'parent_aligned_rms':float(align_cyclic(y,base,1)[1]),
                            'parameters':{'scales':scales.tolist(),'mode':mode,'phase':float(phase)},
                            'topology_status':'SUPPORTED_TREFOIL_DIAGRAM' if passed else 'UNVERIFIED'})
            topology.append({'path':name,'checks':checks})
    okay=all(r['topology_status']=='SUPPORTED_TREFOIL_DIAGRAM' for r in records) and all(p['aligned_rms']>1e-7 for p in pairwise)
    dump_json(test/'source_families.json',{'format':'SST-SOURCE-FAMILIES-1','sources':records})
    dump_json(out/'sealed/TOPOLOGY_WITNESSES.json',topology)
    dump_json(out/'sealed/GEOMETRY_PAIRWISE.json',pairwise)
    summary={'status':'QUALIFIED_PROSPECTIVE_REALIZATION_ATLAS' if okay else 'BLOCKED_ATLAS_QUALIFICATION',
             'family_count':len(parents),'test_count':len(records),'parent_level_held_out':False,
             'topology_status':'SUPPORTED_NUMERICAL_DIAGRAM_NOT_EXTERNAL_PROVIDER_CERTIFIED',
             'test_manifest_sha256':object_sha256(records),'test_files':tree_manifest(test),
             'reserve_status':'SEED_COMMITTED_GEOMETRIES_NOT_GENERATED_NOT_SCORED',
             'source_identity_map_location':'test_atlas/source_families.json (custodian input; not public score output)',
             'blindness_scope':'pipeline identity blinding, not independent human custodian blinding'}
    dump_json(out/'ATLAS_SUMMARY.json',summary)
    if not okay: raise RuntimeError('BLOCKED_ATLAS_QUALIFICATION_NO_REDRAWS_ALLOWED')
    return summary


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('command',choices=['freeze','generate-test','verify'])
    parser.add_argument('repo'); parser.add_argument('out')
    parser.add_argument('--config'); parser.add_argument('--protocol')
    args=parser.parse_args()
    if args.command=='freeze': result=freeze(args.repo,args.out,args.config,args.protocol)
    elif args.command=='generate-test': result=generate_test(args.repo,args.out)
    else: result=verify_freeze(args.repo,args.out)
    print({k:v for k,v in result.items() if k in ['status','format','family_count','test_count','reserve_status','scope']})


if __name__=='__main__': main()
