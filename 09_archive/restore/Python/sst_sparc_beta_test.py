#!/usr/bin/env python3
"""
SST SPARC beta test
===================

Tests whether the inverse rotation-amplitude coherence count obeys

    C_A_obs = xi_A * N_baryon^beta

with special focus on beta = 1/2.

Input
-----
One or more CSV files generated by sst_sparc_inverse_reconstruction_v2/v3.py.
Required columns:
    C_A_obs
    N_baryon

Optional columns used if present:
    Galaxy
    Rbar_kpc
    Vflat_used_kms
    Lambda_local_LPV
    R_tension

Outputs
-------
1. Console summary
2. CSV summary table
3. Optional per-galaxy diagnostics CSV
4. Optional PNG plots if matplotlib is installed and --plots is passed

Example
-------
python sst_sparc_beta_test.py sparc_sst_inverse.csv sparc_sst_inverse_Rlast_Q1.csv

python sst_sparc_beta_test.py sparc_sst_inverse.csv --bootstrap 10000 --plots
"""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np


DEFAULT_R_TENSION = 1.04140219e42


def read_csv_rows(path: Path) -> List[Dict[str, str]]:
    with path.open("r", newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        return list(reader)


def to_float(value: str) -> float:
    try:
        if value is None:
            return float("nan")
        s = str(value).strip()
        if not s:
            return float("nan")
        return float(s)
    except Exception:
        return float("nan")


def normal_two_sided_p_from_z(z: float) -> float:
    return math.erfc(abs(z) / math.sqrt(2.0))


def ols_loglog(x: np.ndarray, y: np.ndarray) -> Dict[str, float]:
    n = len(x)
    xbar = float(np.mean(x))
    ybar = float(np.mean(y))
    dx = x - xbar
    dy = y - ybar
    sxx = float(np.sum(dx * dx))
    sxy = float(np.sum(dx * dy))
    beta = sxy / sxx
    alpha = ybar - beta * xbar
    yhat = alpha + beta * x
    resid = y - yhat
    rss = float(np.sum(resid * resid))
    tss = float(np.sum((y - ybar) ** 2))
    r2 = 1.0 - rss / tss if tss > 0 else float("nan")
    sigma2 = rss / max(n - 2, 1)
    beta_se = math.sqrt(sigma2 / sxx) if sxx > 0 else float("nan")
    alpha_se = math.sqrt(sigma2 * (1.0 / n + xbar * xbar / sxx)) if sxx > 0 else float("nan")
    return {
        "n": n,
        "alpha": alpha,
        "beta": beta,
        "alpha_se": alpha_se,
        "beta_se": beta_se,
        "rss": rss,
        "r2": r2,
        "sigma_ln": math.sqrt(sigma2),
        "sigma_dex": math.sqrt(sigma2) / math.log(10.0),
    }


def fixed_beta_fit(x: np.ndarray, y: np.ndarray, beta0: float = 0.5) -> Dict[str, float]:
    alpha0 = float(np.mean(y - beta0 * x))
    yhat0 = alpha0 + beta0 * x
    resid0 = y - yhat0
    rss0 = float(np.sum(resid0 * resid0))
    sigma_ln0 = math.sqrt(rss0 / max(len(x) - 1, 1))
    z = y - beta0 * x
    xi_values = np.exp(z)
    return {
        "beta_fixed": beta0,
        "alpha_fixed": alpha0,
        "xi_fixed_exp_alpha": math.exp(alpha0),
        "xi_fixed_median": float(np.median(xi_values)),
        "xi_fixed_p16": float(np.quantile(xi_values, 0.16)),
        "xi_fixed_p84": float(np.quantile(xi_values, 0.84)),
        "rss_fixed": rss0,
        "sigma_ln_fixed": sigma_ln0,
        "sigma_dex_fixed": sigma_ln0 / math.log(10.0),
    }


def bootstrap_beta(x: np.ndarray, y: np.ndarray, n_boot: int, seed: int) -> Dict[str, float]:
    if n_boot <= 0:
        return {
            "beta_boot_p025": float("nan"),
            "beta_boot_p50": float("nan"),
            "beta_boot_p975": float("nan"),
            "alpha_boot_p025": float("nan"),
            "alpha_boot_p50": float("nan"),
            "alpha_boot_p975": float("nan"),
        }

    rng = np.random.default_rng(seed)
    n = len(x)
    betas = np.empty(n_boot)
    alphas = np.empty(n_boot)
    for i in range(n_boot):
        idx = rng.integers(0, n, n)
        fit = ols_loglog(x[idx], y[idx])
        betas[i] = fit["beta"]
        alphas[i] = fit["alpha"]

    return {
        "beta_boot_p025": float(np.quantile(betas, 0.025)),
        "beta_boot_p50": float(np.quantile(betas, 0.50)),
        "beta_boot_p975": float(np.quantile(betas, 0.975)),
        "alpha_boot_p025": float(np.quantile(alphas, 0.025)),
        "alpha_boot_p50": float(np.quantile(alphas, 0.50)),
        "alpha_boot_p975": float(np.quantile(alphas, 0.975)),
    }


def analyze_file(path: Path, beta0: float, n_boot: int, seed: int) -> Tuple[Dict[str, float], List[Dict[str, float]]]:
    rows = read_csv_rows(path)
    clean = []
    for row in rows:
        c = to_float(row.get("C_A_obs"))
        n = to_float(row.get("N_baryon"))
        if math.isfinite(c) and c > 0 and math.isfinite(n) and n > 0:
            clean.append((row, c, n))

    if len(clean) < 3:
        raise RuntimeError(f"{path}: not enough valid rows with C_A_obs and N_baryon")

    C = np.array([c for _, c, _ in clean], dtype=float)
    N = np.array([n for _, _, n in clean], dtype=float)
    x = np.log(N)
    y = np.log(C)

    free = ols_loglog(x, y)
    fixed = fixed_beta_fit(x, y, beta0=beta0)
    boot = bootstrap_beta(x, y, n_boot=n_boot, seed=seed)

    beta = free["beta"]
    beta_se = free["beta_se"]
    z = (beta - beta0) / beta_se if beta_se > 0 else float("nan")
    p_approx = normal_two_sided_p_from_z(z) if math.isfinite(z) else float("nan")

    # BIC comparison: positive delta means free-beta model is preferred over fixed beta.
    nobs = len(x)
    bic_free = nobs * math.log(free["rss"] / nobs) + 2 * math.log(nobs)
    bic_fixed = nobs * math.log(fixed["rss_fixed"] / nobs) + 1 * math.log(nobs)
    delta_bic_fixed_minus_free = bic_fixed - bic_free

    # Random-walk residual diagnostics.
    R_RW = C / np.sqrt(N)
    log_R_RW = np.log(R_RW)
    # Slope of log(C/sqrtN) versus logN should be 0 if beta=1/2.
    rw_fit = ols_loglog(x, log_R_RW)

    # p_chi amplitude diagnostic if possible.
    lambda_local_values = []
    r_tension_values = []
    for row, _, _ in clean:
        lambda_local_values.append(to_float(row.get("Lambda_local_LPV")))
        r_tension_values.append(to_float(row.get("R_tension")))
    lambda_local_arr = np.array(lambda_local_values, dtype=float)
    r_tension_arr = np.array(r_tension_values, dtype=float)

    lambda_local = float(np.nanmedian(lambda_local_arr)) if np.isfinite(lambda_local_arr).any() else float("nan")
    r_tension = float(np.nanmedian(r_tension_arr)) if np.isfinite(r_tension_arr).any() else DEFAULT_R_TENSION
    if not math.isfinite(r_tension) or r_tension <= 1:
        r_tension = DEFAULT_R_TENSION

    if math.isfinite(lambda_local) and lambda_local > 0:
        p_amp = np.log(lambda_local * C) / math.log(r_tension)
        p_amp_median = float(np.median(p_amp))
        p_amp_p16 = float(np.quantile(p_amp, 0.16))
        p_amp_p84 = float(np.quantile(p_amp, 0.84))
    else:
        p_amp = np.full_like(C, np.nan)
        p_amp_median = p_amp_p16 = p_amp_p84 = float("nan")

    summary = {
        "file": str(path),
        "n": nobs,
        "beta_free": beta,
        "beta_se": beta_se,
        "beta_ci95_normal_low": beta - 1.96 * beta_se,
        "beta_ci95_normal_high": beta + 1.96 * beta_se,
        "z_vs_beta0": z,
        "p_approx_vs_beta0": p_approx,
        "r2_loglog": free["r2"],
        "sigma_dex_free": free["sigma_dex"],
        "alpha_free": free["alpha"],
        "xi_free_at_N1": math.exp(free["alpha"]),
        "beta0": beta0,
        **fixed,
        "delta_bic_fixed_minus_free": delta_bic_fixed_minus_free,
        "R_RW_median": float(np.median(R_RW)),
        "R_RW_p16": float(np.quantile(R_RW, 0.16)),
        "R_RW_p84": float(np.quantile(R_RW, 0.84)),
        "log_R_RW_slope_vs_logN": rw_fit["beta"],
        "log_R_RW_slope_se": rw_fit["beta_se"],
        "p_amp_median": p_amp_median,
        "p_amp_p16": p_amp_p16,
        "p_amp_p84": p_amp_p84,
        **boot,
    }

    per_rows = []
    for i, (row, c, n) in enumerate(clean):
        expected_fixed = math.exp(fixed["alpha_fixed"]) * (n ** beta0)
        residual_ln = math.log(c) - math.log(expected_fixed)
        per_rows.append({
            "source_file": str(path),
            "Galaxy": row.get("Galaxy", ""),
            "N_baryon": n,
            "C_A_obs": c,
            "C_A_over_sqrtN": c / math.sqrt(n),
            "C_A_pred_beta_fixed": expected_fixed,
            "residual_ln_beta_fixed": residual_ln,
            "residual_dex_beta_fixed": residual_ln / math.log(10.0),
            "p_chi_amp": float(p_amp[i]) if i < len(p_amp) and math.isfinite(p_amp[i]) else float("nan"),
            "Rbar_kpc": to_float(row.get("Rbar_kpc")),
            "Vflat_used_kms": to_float(row.get("Vflat_used_kms")),
        })

    return summary, per_rows


def write_csv(path: Path, rows: List[Dict[str, object]]) -> None:
    if not rows:
        return
    fieldnames = list(rows[0].keys())
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def maybe_make_plots(files: List[Path], output_dir: Path, beta0: float) -> None:
    try:
        import matplotlib.pyplot as plt
    except Exception:
        print("matplotlib not available; skipping plots.")
        return

    output_dir.mkdir(parents=True, exist_ok=True)

    for path in files:
        rows = read_csv_rows(path)
        C_list = []
        N_list = []
        for row in rows:
            c = to_float(row.get("C_A_obs"))
            n = to_float(row.get("N_baryon"))
            if math.isfinite(c) and c > 0 and math.isfinite(n) and n > 0:
                C_list.append(c)
                N_list.append(n)

        C = np.array(C_list)
        N = np.array(N_list)
        x = np.log(N)
        y = np.log(C)
        free = ols_loglog(x, y)
        fixed = fixed_beta_fit(x, y, beta0=beta0)

        n_grid = np.logspace(np.log10(N.min()), np.log10(N.max()), 200)
        c_free = math.exp(free["alpha"]) * n_grid ** free["beta"]
        c_fixed = math.exp(fixed["alpha_fixed"]) * n_grid ** beta0

        plt.figure(figsize=(7, 5))
        plt.scatter(N, C, s=18, alpha=0.75)
        plt.plot(n_grid, c_free, label=f"free beta={free['beta']:.3f}")
        plt.plot(n_grid, c_fixed, linestyle="--", label=f"fixed beta={beta0:.3f}")
        plt.xscale("log")
        plt.yscale("log")
        plt.xlabel("N_baryon")
        plt.ylabel("C_A_obs")
        plt.title(path.stem)
        plt.legend()
        plt.tight_layout()
        plt.savefig(output_dir / f"{path.stem}_beta_fit.png", dpi=160)
        plt.close()


def main() -> None:
    parser = argparse.ArgumentParser(description="Test C_A_obs ∝ N_baryon^beta and beta=1/2")
    parser.add_argument("csv_files", nargs="+", help="CSV files from SST SPARC inverse reconstruction")
    parser.add_argument("--beta0", type=float, default=0.5, help="Null/fixed beta to test")
    parser.add_argument("--bootstrap", type=int, default=5000, help="Bootstrap resamples for beta CI")
    parser.add_argument("--seed", type=int, default=12345, help="Random seed")
    parser.add_argument("--summary-out", default="sparc_beta_test_summary.csv", help="Output summary CSV")
    parser.add_argument("--per-galaxy-out", default="sparc_beta_test_per_galaxy.csv", help="Output per-galaxy CSV")
    parser.add_argument("--plots", action="store_true", help="Save log-log fit plots")
    parser.add_argument("--plot-dir", default="sparc_beta_plots", help="Plot output directory")
    args = parser.parse_args()

    summaries = []
    per_rows_all = []
    paths = [Path(p) for p in args.csv_files]

    for path in paths:
        summary, per_rows = analyze_file(path, beta0=args.beta0, n_boot=args.bootstrap, seed=args.seed)
        summaries.append(summary)
        per_rows_all.extend(per_rows)

    write_csv(Path(args.summary_out), summaries)
    write_csv(Path(args.per_galaxy_out), per_rows_all)

    if args.plots:
        maybe_make_plots(paths, Path(args.plot_dir), beta0=args.beta0)

    print("\nSST SPARC beta test complete.")
    print(f"Summary:    {args.summary_out}")
    print(f"Per-galaxy: {args.per_galaxy_out}")
    print("\nKey results:")
    for s in summaries:
        print(f"\n{s['file']}")
        print(f"  n                         = {int(s['n'])}")
        print(f"  beta_free                 = {s['beta_free']:.6f} ± {s['beta_se']:.6f}")
        print(f"  95% normal CI             = [{s['beta_ci95_normal_low']:.6f}, {s['beta_ci95_normal_high']:.6f}]")
        print(f"  bootstrap 95% CI          = [{s['beta_boot_p025']:.6f}, {s['beta_boot_p975']:.6f}]")
        print(f"  z vs beta0={args.beta0:g}           = {s['z_vs_beta0']:.3f}")
        print(f"  approx p vs beta0         = {s['p_approx_vs_beta0']:.3e}")
        print(f"  R^2 log-log               = {s['r2_loglog']:.6f}")
        print(f"  sigma dex free            = {s['sigma_dex_free']:.6f}")
        print(f"  fixed beta xi median      = {s['xi_fixed_median']:.6e}")
        print(f"  fixed beta xi p16-p84     = [{s['xi_fixed_p16']:.6e}, {s['xi_fixed_p84']:.6e}]")
        print(f"  R_RW median               = {s['R_RW_median']:.6e}")
        print(f"  log(R_RW) slope vs logN   = {s['log_R_RW_slope_vs_logN']:.6f} ± {s['log_R_RW_slope_se']:.6f}")
        print(f"  p_chi_amp median p16-p84  = {s['p_amp_median']:.6f} [{s['p_amp_p16']:.6f}, {s['p_amp_p84']:.6f}]")
        print(f"  Delta BIC fixed-free      = {s['delta_bic_fixed_minus_free']:.3f}  (positive favors free beta)")


if __name__ == "__main__":
    main()
