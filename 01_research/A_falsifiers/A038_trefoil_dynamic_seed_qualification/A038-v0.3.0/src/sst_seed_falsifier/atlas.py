"""Prospective realization holdout with pinned SST Knot Library source records.

Freeze -> generate test shard -> score -> reveal. Reserve random seed remains
sealed and reserve geometries are deliberately not generated by this module.
The atlas is realization-held-out only; historical parents are not unseen.
"""
from pathlib import Path
from datetime import datetime, timezone
import argparse
import secrets
import numpy as np

from .evidence import code_manifest, file_sha256, object_sha256, tree_manifest
from .io import dump_json, load_json, geom_sha
from .geometry import normalize_length, resample_closed, normal_frame, align_cyclic
from .topology_witness import trefoil_witness
from .knot_library import activate, current_attestation, make_source_record, generate_braid_trefoil

PARENTS = {
    'fremlin_fourier': 'Fremlin_FourierSeries/fremlin/3_1/knot.3_1.short',
    'gilbert_sono_fourier': 'Knot_Library/Sources/Ideal_Gilbert/extracted/3_1/3_1_AB.txt',
}


def dependencies(repo,cfg):
    repo=Path(repo)
    rows=[{'path':p,'sha256':file_sha256(repo/p),'bytes':(repo/p).stat().st_size} for p in PARENTS.values()]
    att=activate(repo,cfg)
    return {'parent_files':rows,'knot_library':att}


def freeze(repo, out, config, protocol):
    out=Path(out); private=out/'sealed'
    if out.exists() and any(out.iterdir()): raise FileExistsError('REFUSING_TO_OVERWRITE_ATLAS')
    private.mkdir(parents=True)
    cfg=load_json(config); phase=load_json(protocol)
    dep=dependencies(repo,cfg)
    test_seed=secrets.token_hex(32); reserve_seed=secrets.token_hex(32)
    dump_json(private/'seeds.json',{'test':test_seed,'reserve':reserve_seed})
    package=Path(__file__).resolve().parents[2]
    record={'format':'SST-PROSPECTIVE-ATLAS-2','created_utc':datetime.now(timezone.utc).isoformat(),
            'scope':'new_randomized_realizations_of_previously_available_parent_families',
            'parent_level_held_out':False,'statistical_independence_claim':False,
            'families':['fremlin_fourier','gilbert_sono_fourier','sst_braid_closure'],
            'independence_basis':'distinct_geometry_construction_lineages_not_independent_physical_observations',
            'test_seed_sha256':object_sha256(test_seed),'reserve_seed_sha256':object_sha256(reserve_seed),
            'code_manifest':code_manifest(package),'dependencies':dep,
            'config':cfg,'phase_b_protocol':phase,
            'config_file_sha256':file_sha256(config),'protocol_file_sha256':file_sha256(protocol),
            'design':{'test_draws_per_family':2,'reserve_draws_per_family':2,'n':128,
                      'scale_range':[.985,1.015],'normal_amplitude':.003,'modes':[2,3,4],
                      'replacement_on_failure':False,'qualification_resolutions':[64,96,128]},
            'topology_contract':{
                'expected_topology':'3_1','components':1,
                'reference':'pinned KAtlas snapshot through SST Knot Library',
                'geometry_support':'independent float64 trefoil projection witness at N=64,96,128',
                'external_provider_certification_required_for_publication':True,
                'scientific_screen_admission':'reference_plus_numerical_diagram_support_not_external_certification',
            }}
    dump_json(out/'PREREGISTRATION.json',record); dump_json(out/'PREREGISTRATION_COMMITMENT.json',{'sha256':object_sha256(record)})
    return record


def verify_freeze(repo,out):
    out=Path(out); record=load_json(out/'PREREGISTRATION.json')
    if object_sha256(record)!=load_json(out/'PREREGISTRATION_COMMITMENT.json')['sha256']: raise ValueError('ATLAS_PROTOCOL_COMMITMENT_MISMATCH')
    if record['code_manifest']!=code_manifest(Path(__file__).resolve().parents[2]): raise ValueError('ATLAS_FROZEN_CODE_MISMATCH')
    if record['dependencies']!=dependencies(repo,record['config']): raise ValueError('ATLAS_FROZEN_DEPENDENCY_MISMATCH')
    return record


def load_parents(repo,cfg):
    repo=Path(repo); activate(repo,cfg); out={}
    for family,rel in PARENTS.items():
        p=repo/rel; x,rec,h=make_source_record(p,expected='3_1',n=512,relative_path=rel)
        out[family]={'points':x,'record':rec,'record_sha256':h,'provenance':rel}
    x,rec,h=generate_braid_trefoil(512)
    out['sst_braid_closure']={'points':x,'record':rec,'record_sha256':h,
                              'provenance':'SST Knot Library pinned KAtlas braid closure for 3_1'}
    return out


def generate_test(repo,out):
    out=Path(out); record=verify_freeze(repo,out); cfg=record['config']
    if cfg.get('require_knot_library_records',False): activate(repo,cfg)
    test=out/'test_atlas'
    if test.exists(): raise FileExistsError('TEST_ATLAS_ALREADY_GENERATED')
    seeds=load_json(out/'sealed/seeds.json')
    if object_sha256(seeds['test'])!=record['test_seed_sha256']: raise ValueError('ATLAS_TEST_SEED_COMMITMENT_MISMATCH')
    rng=np.random.default_rng(int(seeds['test'],16)); design=record['design']; parents=load_parents(repo,cfg); test.mkdir()
    records=[]; geometries=[]; topology=[]; pairwise=[]; knot_records=[]
    for fi,(family,parent_info) in enumerate(parents.items()):
        parent=np.asarray(parent_info['points'],float)
        base=normalize_length(resample_closed(parent,design['n']))
        for draw in range(design['test_draws_per_family']):
            scales=rng.uniform(*design['scale_range'],size=3); y=base*scales
            _,normal,_=normal_frame(y); phase=rng.uniform(0,2*np.pi); mode=int(rng.choice(design['modes']))
            y=y+design['normal_amplitude']*np.cos(2*np.pi*mode*np.arange(len(y))/len(y)+phase)[:,None]*normal
            y=normalize_length(resample_closed(y,design['n']))
            name=f'trefoil_family{fi+1}_draw{draw+1}.xyz'; path=test/name
            np.savetxt(path,np.vstack([y,y[0]]),fmt='%.17g')
            # Bind the actual generated file bytes to a portable KnotRecord using the pinned library.
            _canon,krec,khash=make_source_record(path,expected='3_1',n=design['n'],relative_path=name)
            checks={str(n):trefoil_witness(normalize_length(resample_closed(y,n))) for n in design['qualification_resolutions']}
            passed=all(c['accepted'] for c in checks.values())
            for previous,z in geometries:
                d=min(align_cyclic(y,z,1)[1],align_cyclic(y[::-1],z,1)[1]); pairwise.append({'a':previous,'b':name,'aligned_rms':float(d)})
            geometries.append((name,y)); topology.append({'path':name,'checks':checks})
            knot_records.append({'path':name,'record':krec,'record_sha256':khash})
            kprov=krec.get('provenance',{}); kgeom=krec.get('geometry',{}); kcert=krec.get('topology_certification',{})
            records.append({'path':name,'family_id':family,'topology':'3_1','components':1,
                            'held_out':True,'held_out_scope':'prospective_randomized_realization_only','parent_level_held_out':False,
                            'provenance':parent_info['provenance'],'parent_knot_record_sha256':parent_info['record_sha256'],
                            'geometry_sha256':geom_sha(y),'file_sha256':file_sha256(path),'parent_geom_sha256':geom_sha(base),
                            'parent_aligned_rms':float(align_cyclic(y,base,1)[1]),
                            'parameters':{'scales':scales.tolist(),'mode':mode,'phase':float(phase)},
                            'topology_status':'SUPPORTED_NUMERICAL_DIAGRAM_NOT_EXTERNAL_PROVIDER_CERTIFIED' if passed else 'UNVERIFIED',
                            'topology_witness_status':'SUPPORTED_TREFOIL_DIAGRAM' if passed else 'UNVERIFIED',
                            'knot_record_sha256':khash,'knot_record_resample_n':int(design['n']),
                            'knot_library_version':current_attestation()['runtime_version'],
                            'katlas_snapshot_id':current_attestation()['katlas_snapshot_id'],
                            'katlas_snapshot_sha256':current_attestation()['katlas_snapshot_sha256'],
                            'source_provider_id':kgeom.get('source_provider',{}).get('provider_id'),
                            'source_family':kgeom.get('source_family'),
                            'knot_library_topology_certification':kcert.get('status'),
                            'knot_library_provenance':kprov})
    okay=(all(r['topology_witness_status']=='SUPPORTED_TREFOIL_DIAGRAM' for r in records)
          and all(p['aligned_rms']>1e-7 for p in pairwise)
          and all(r['knot_record_sha256'] for r in records))
    dump_json(test/'source_families.json',{'format':'SST-SOURCE-FAMILIES-2','sources':records,
                                          'knot_library_dependency':current_attestation()})
    dump_json(out/'sealed/TOPOLOGY_WITNESSES.json',topology); dump_json(out/'sealed/GEOMETRY_PAIRWISE.json',pairwise)
    dump_json(out/'sealed/KNOT_LIBRARY_RECORDS.json',{'records':knot_records,'dependency':current_attestation()})
    summary={'status':'QUALIFIED_PROSPECTIVE_REALIZATION_ATLAS' if okay else 'BLOCKED_ATLAS_QUALIFICATION',
             'family_count':len(parents),'test_count':len(records),'parent_level_held_out':False,
             'topology_status':'SUPPORTED_NUMERICAL_DIAGRAM_NOT_EXTERNAL_PROVIDER_CERTIFIED',
             'knot_record_binding_status':'PASS' if okay else 'FAILED',
             'knot_library_dependency':current_attestation(),
             'test_manifest_sha256':object_sha256(records),'test_files':tree_manifest(test),
             'reserve_status':'SEED_COMMITTED_GEOMETRIES_NOT_GENERATED_NOT_SCORED',
             'source_identity_map_location':'test_atlas/source_families.json (custodian input; not public score output)',
             'blindness_scope':'pipeline identity blinding, not independent human custodian blinding'}
    dump_json(out/'ATLAS_SUMMARY.json',summary)
    if not okay: raise RuntimeError('BLOCKED_ATLAS_QUALIFICATION_NO_REDRAWS_ALLOWED')
    return summary


def main():
    parser=argparse.ArgumentParser(); parser.add_argument('command',choices=['freeze','generate-test','verify'])
    parser.add_argument('repo'); parser.add_argument('out'); parser.add_argument('--config'); parser.add_argument('--protocol'); args=parser.parse_args()
    if args.command=='freeze': result=freeze(args.repo,args.out,args.config,args.protocol)
    elif args.command=='generate-test': result=generate_test(args.repo,args.out)
    else: result=verify_freeze(args.repo,args.out)
    print({k:v for k,v in result.items() if k in ['status','format','family_count','test_count','reserve_status','scope']})

if __name__=='__main__': main()
